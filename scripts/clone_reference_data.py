"""Copy shared reference data from one database into a new client's database.

Why this exists
---------------
A new client organisation is onboarded into its **own** Postgres database. It
starts with the same procedure codes, fee schedules, letter templates, note
macros and prescription library as the source database; everything else
(offices, providers, users, insurance, fee-schedule assignments) the client
configures in Setup. No seeder covers these tables, so they are copied.

What is copied
--------------
* Global tables (no ``tenant_id``): ``procedure_codes``, ``permissions``,
  ``icd_codes`` — **insert-missing** by natural key (``code``), never overwrite.
  ``procedure_codes``' pointers at tenant rows (``default_material_id``,
  ``default_provider_id``, ``default_notes_macro_id``) are NULLed: those ids
  mean nothing in the target.
* Tenant tables, from ``--source-tenant`` into ``--target-tenant``:
  ``fee_schedules`` (+ ``fee_schedule_entries``), ``letter_templates``,
  ``note_macros``, ``prescription_library``. Ids are regenerated by the target
  (so sequences stay correct) and remapped where referenced
  (``fee_schedule_entries.fee_schedule_id``, ``fee_schedules.parent_schedule_id``).
  Pointers at things the client has not created yet — ``office_id``,
  ``ins_plan_id`` and the ``created_by``/``updated_by`` users — are NULLed.

Deliberately **not** copied: ``fee_schedule_assignments`` and
``offices.default_fee_schedule_id`` — those bind schedules to the client's own
offices/providers/plans and are set in the Fee Schedule Wizard.

Columns are **reflected** from both databases and only the intersection is
copied, so a source DB a revision or two behind the target (or vice versa)
still clones.

Re-runs
-------
``fee_schedules`` has no natural key a re-run could match on, so if the target
tenant already holds rows in a tenant table the script refuses, unless
``--skip-existing`` is passed (that table is then skipped).

Usage
-----
Dry-run by default (everything runs inside a transaction that is rolled back,
so the counts are exact)::

    python -m scripts.clone_reference_data --source-url postgresql+psycopg2://.../recondental_migrated \\
        --target-url postgresql+psycopg2://.../newclient --source-tenant 1 --target-tenant 1
    python -m scripts.clone_reference_data ... --apply
    python -m scripts.clone_reference_data ... --apply --active-only
"""

from __future__ import annotations

import argparse
from collections.abc import Iterable

from sqlalchemy import MetaData, Table, create_engine, insert, select
from sqlalchemy.engine import Connection

BATCH_SIZE = 2000

# Global tables: (table, natural key, columns to NULL).
GLOBAL_TABLES: list[tuple[str, str, tuple[str, ...]]] = [
    (
        "procedure_codes",
        "code",
        ("default_material_id", "default_provider_id", "default_notes_macro_id"),
    ),
    ("permissions", "code", ()),
    ("icd_codes", "code", ()),
]

# Tenant tables copied as independent rows: (table, columns to NULL).
SIMPLE_TENANT_TABLES: list[tuple[str, tuple[str, ...]]] = [
    ("letter_templates", ()),
    ("note_macros", ("created_by", "updated_by")),
    ("prescription_library", ("created_by", "updated_by")),
]

FEE_SCHEDULE_NULLS = ("office_id", "ins_plan_id", "created_by", "updated_by")
FEE_ENTRY_NULLS = ("created_by", "updated_by")

# Tenant tables the re-run guard inspects.
GUARDED_TABLES = ("fee_schedules", *(t for t, _ in SIMPLE_TENANT_TABLES))


def _reflect(conn: Connection, names: Iterable[str]) -> dict[str, Table]:
    md = MetaData()
    md.reflect(bind=conn, only=list(names))
    return dict(md.tables)


def _shared_columns(src: Table, dst: Table, *, drop: Iterable[str] = ("id",)) -> list[str]:
    """Columns present in both tables, minus the regenerated PK."""
    dropped = set(drop)
    return [c.name for c in dst.columns if c.name in src.c and c.name not in dropped]


def _chunks(rows: list[dict], size: int = BATCH_SIZE) -> Iterable[list[dict]]:
    for i in range(0, len(rows), size):
        yield rows[i : i + size]


def _prepare(row: dict, nulls: Iterable[str], **overrides) -> dict:
    out = dict(row)
    for col in nulls:
        if col in out:
            out[col] = None
    out.update(overrides)
    return out


# ── Global tables ────────────────────────────────────────────────────────────


def copy_global(src: Connection, dst: Connection, src_t: dict, dst_t: dict) -> dict[str, int]:
    counts: dict[str, int] = {}
    for name, key, nulls in GLOBAL_TABLES:
        s, d = src_t[name], dst_t[name]
        # Keep a natural-key table's own ``id`` out: the target sequence assigns it.
        drop = ("id",) if key != "id" and "id" in d.c else ()
        cols = _shared_columns(s, d, drop=drop)
        existing = set(dst.execute(select(d.c[key])).scalars())
        rows = [
            _prepare(dict(r._mapping), nulls)
            for r in src.execute(select(*(s.c[c] for c in cols)).order_by(s.c[key]))
            if r._mapping[key] not in existing
        ]
        for chunk in _chunks(rows):
            dst.execute(insert(d), chunk)
        counts[name] = len(rows)
    return counts


# ── Tenant tables ────────────────────────────────────────────────────────────


def _source_rows(src: Connection, table: Table, cols: list[str], tenant: int, active_only: bool):
    stmt = select(*(table.c[c] for c in cols)).where(table.c.tenant_id == tenant)
    if active_only and "is_active" in table.c:
        stmt = stmt.where(table.c.is_active.is_(True))
    return [dict(r._mapping) for r in src.execute(stmt.order_by(table.c.id))]


def copy_fee_schedules(
    src: Connection, dst: Connection, src_t: dict, dst_t: dict,
    source_tenant: int, target_tenant: int, *, active_only: bool,
) -> tuple[int, int]:
    s, d = src_t["fee_schedules"], dst_t["fee_schedules"]
    cols = ["id", *_shared_columns(s, d)]
    schedules = _source_rows(src, s, cols, source_tenant, active_only)

    id_map: dict[int, int] = {}
    for row in schedules:
        old_id = row.pop("id")
        values = _prepare(row, (*FEE_SCHEDULE_NULLS, "parent_schedule_id"), tenant_id=target_tenant)
        id_map[old_id] = dst.execute(insert(d).values(**values).returning(d.c.id)).scalar_one()

    # Second pass: a parent may have been inserted after its child.
    if "parent_schedule_id" in d.c and "parent_schedule_id" in s.c and id_map:
        parents = src.execute(
            select(s.c.id, s.c.parent_schedule_id).where(
                s.c.id.in_(list(id_map)), s.c.parent_schedule_id.is_not(None)
            )
        ).all()
        for old_id, old_parent in parents:
            if old_parent in id_map:
                dst.execute(
                    d.update().where(d.c.id == id_map[old_id])
                    .values(parent_schedule_id=id_map[old_parent])
                )

    se, de = src_t["fee_schedule_entries"], dst_t["fee_schedule_entries"]
    ecols = _shared_columns(se, de)
    entries = []
    if id_map:
        stmt = select(*(se.c[c] for c in ecols)).where(se.c.fee_schedule_id.in_(list(id_map)))
        for r in src.execute(stmt.order_by(se.c.id)):
            row = dict(r._mapping)
            entries.append(
                _prepare(row, FEE_ENTRY_NULLS, tenant_id=target_tenant,
                         fee_schedule_id=id_map[row["fee_schedule_id"]])
            )
    for chunk in _chunks(entries):
        dst.execute(insert(de), chunk)
    return len(schedules), len(entries)


def copy_simple(
    src: Connection, dst: Connection, src_t: dict, dst_t: dict, name: str,
    nulls: tuple[str, ...], source_tenant: int, target_tenant: int, *, active_only: bool,
) -> int:
    s, d = src_t[name], dst_t[name]
    cols = _shared_columns(s, d)
    rows = [
        _prepare(r, nulls, tenant_id=target_tenant)
        for r in _source_rows(src, s, cols, source_tenant, active_only)
    ]
    for chunk in _chunks(rows):
        dst.execute(insert(d), chunk)
    return len(rows)


# ── Driver ───────────────────────────────────────────────────────────────────


def tables_with_rows(dst: Connection, dst_t: dict, tenant: int) -> list[str]:
    return [
        name for name in GUARDED_TABLES
        if dst.execute(
            select(dst_t[name].c.id).where(dst_t[name].c.tenant_id == tenant).limit(1)
        ).first()
    ]


def clone(
    src: Connection, dst: Connection, source_tenant: int, target_tenant: int,
    *, active_only: bool = False, skip_existing: bool = False,
) -> dict[str, int]:
    names = [*(t for t, _, _ in GLOBAL_TABLES), "fee_schedules", "fee_schedule_entries",
             *(t for t, _ in SIMPLE_TENANT_TABLES), "tenants"]
    src_t, dst_t = _reflect(src, names), _reflect(dst, names)

    tenants = dst_t["tenants"]
    if not dst.execute(select(tenants.c.id).where(tenants.c.id == target_tenant)).first():
        raise SystemExit(f"target tenant {target_tenant} does not exist in the target DB — "
                         "create it first (POST /api/v1/auth/signup)")

    populated = tables_with_rows(dst, dst_t, target_tenant)
    if populated and not skip_existing:
        raise SystemExit(
            f"target tenant {target_tenant} already has rows in: {', '.join(populated)}. "
            "Re-run with --skip-existing to skip those tables."
        )

    counts = copy_global(src, dst, src_t, dst_t)
    if "fee_schedules" not in populated:
        counts["fee_schedules"], counts["fee_schedule_entries"] = copy_fee_schedules(
            src, dst, src_t, dst_t, source_tenant, target_tenant, active_only=active_only
        )
    for name, nulls in SIMPLE_TENANT_TABLES:
        if name not in populated:
            counts[name] = copy_simple(
                src, dst, src_t, dst_t, name, nulls, source_tenant, target_tenant,
                active_only=active_only,
            )
    for name in populated:
        counts[name] = 0
    return counts


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--source-url", required=True, help="SQLAlchemy URL of the source DB")
    parser.add_argument("--target-url", required=True, help="SQLAlchemy URL of the new client DB")
    parser.add_argument("--source-tenant", type=int, required=True)
    parser.add_argument("--target-tenant", type=int, required=True)
    parser.add_argument("--apply", action="store_true", help="commit (default: dry run)")
    parser.add_argument("--active-only", action="store_true",
                        help="skip inactive fee schedules / templates / Rx rows")
    parser.add_argument("--skip-existing", action="store_true",
                        help="skip tenant tables the target tenant already has rows in")
    args = parser.parse_args()

    if args.source_url == args.target_url:
        raise SystemExit("source and target URLs are the same database")

    src_engine, dst_engine = create_engine(args.source_url), create_engine(args.target_url)
    with src_engine.connect() as src, dst_engine.connect() as dst:
        txn = dst.begin()
        try:
            counts = clone(src, dst, args.source_tenant, args.target_tenant,
                           active_only=args.active_only, skip_existing=args.skip_existing)
        except BaseException:
            txn.rollback()
            raise
        verb = "copied" if args.apply else "would copy"
        for name, n in counts.items():
            print(f"{name:<24} {verb} {n:>7}")
        if args.apply:
            txn.commit()
        else:
            txn.rollback()
            print("\nDry run - nothing written. Re-run with --apply.")


if __name__ == "__main__":
    main()
